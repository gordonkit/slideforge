export type Locale = "en" | "zh-TW" | "zh-CN" | "ja";

export type Text = Record<Locale, string>;

/** A table cell is either literal text shared by every locale, such as code, or translated text. */
export type Cell = string | Text;

export type Section = {
  id: string;
  title: Text;
  body: Text;
  bodyLink?: {
    label: Text;
    href: string;
  };
  code?: string;
  bullets?: Record<Locale, string[]>;
  note?: Text;
  links?: Array<{
    label: Text;
    href: string;
  }>;
  interfaces?: Array<{
    title: Text;
    label: Text;
    body: Text;
    example: string;
  }>;
  table?: {
    caption: Text;
    headers: Cell[];
    rows: Cell[][];
  };
  /** Screenshots from public/screenshots/, regenerated by `npm run docs:screenshots` in the repository root. */
  images?: Array<{
    src: string;
    alt: Text;
    caption?: Text | string;
    /** Shown at its own small size instead of the column width, for tall crops. */
    narrow?: boolean;
  }>;
};

